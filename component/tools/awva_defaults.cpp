// awva_defaults <engine> <out.h>: an engine's parameter defaults (their values after init()) as
// the specialisation of nsc::defaults<E> its component compiles in (component/CMakeLists.txt).
// The values are written as hex floats: bit for bit what the engine holds.
#include <cstdio>
#include <string>

#include "awva_sdk/engines.h"

int main(int argc, char** argv) {
	if (argc < 3) {
		std::fprintf(stderr, "usage: awva_defaults <engine> <out.h>\n");
		return 2;
	}
	const awva::sdk::EngineEntry* e = awva::sdk::find_engine(argv[1]);
	if (!e) {
		std::fprintf(stderr, "awva_defaults: no engine %s\n", argv[1]);
		return 2;
	}
	awva::sdk::Engine eng(*e);
	eng.init(48000, 10);
	std::string s = "// generated by awva_defaults: the parameters of " + std::string(argv[1]) + " after init()\n";
	s += "template <> float nsc::defaults<awva::engines::" + std::string(argv[1]) + ">(int i) {\n\tstatic const float d[] = {";
	const int n = eng.num_params();
	for (int i = 0; i < n; i++) {
		char b[48];
		const float* p = eng.param(i);
		std::snprintf(b, sizeof b, "%s%af", i ? ", " : "", p ? static_cast<double>(*p) : 0.0);
		s += b;
	}
	if (n == 0) s += "0.0f";
	s += "};\n\treturn i >= 0 && i < " + std::to_string(n) + " ? d[i] : 0.0f;\n}\n";
	FILE* f = std::fopen(argv[2], "wb");
	if (!f) return 1;
	std::fputs(s.c_str(), f);
	std::fclose(f);
	return 0;
}
