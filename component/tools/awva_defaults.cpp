// awva_defaults <engine> <out.h>: an engine's parameter defaults (their values after init()) as
// the constant array nsc::defaults_v<E> (and its length, nsc::defaults_count_v<E>) its component
// compiles in (component/CMakeLists.txt).
// The values are written as hex floats: bit for bit what the engine holds.
#include <cstdio>
#include <string>

#include "awva_sdk/engines.h"

int main(int argc, char** argv) {
	if (argc < 3) {
		std::fprintf(stderr, "usage: awva_defaults <engine> <out.h>\n");
		return 2;
	}
	const awva::sdk::EngineEntry* e = awva::sdk::find_engine(argv[1]);
	if (!e) {
		std::fprintf(stderr, "awva_defaults: no engine %s\n", argv[1]);
		return 2;
	}
	awva::sdk::Engine eng(*e);
	eng.init(48000, 10);
	const std::string id = argv[1];
	std::string s = "// generated by awva_defaults: the parameters of " + id + " after init()\n";
	s += "namespace nsc {\nnamespace declared_defaults {\ninline constexpr float " + id + "[] = {";
	const int n = eng.num_params();
	for (int i = 0; i < n; i++) {
		char b[48];
		const float* p = eng.param(i);
		std::snprintf(b, sizeof b, "%s%af", i ? ", " : "", p ? static_cast<double>(*p) : 0.0);
		s += b;
	}
	if (n == 0) s += "0.0f";
	s += "};\n} // namespace declared_defaults\ntemplate <> inline constexpr const float* defaults_v<awva::engines::" + id + "> = declared_defaults::" + id + ";\n";
	s += "template <> inline constexpr int defaults_count_v<awva::engines::" + id + "> = " + std::to_string(n) + ";\n} // namespace nsc\n";
	FILE* f = std::fopen(argv[2], "wb");
	if (!f) return 1;
	std::fputs(s.c_str(), f);
	std::fclose(f);
	return 0;
}
